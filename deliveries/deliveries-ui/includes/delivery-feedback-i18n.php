function deliveries_feedback_resolve_lang(?string $requested = null): string
{
    $langs = deliveries_feedback_languages();
    $requested = strtolower(trim((string) $requested));
    if ($requested !== '' && isset($langs[$requested])) {
        return $requested;
    }
    if (!empty($_COOKIE['dn_feedback_lang'])) {
        $cookie = strtolower(trim((string) $_COOKIE['dn_feedback_lang']));
        if (isset($langs[$cookie])) {
            return $cookie;
        }
    }
    $accept = strtolower((string) ($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));
    foreach (['sw', 'fr', 'ar', 'en'] as $code) {
        if ($accept !== '' && str_contains($accept, $code)) {
            return $code;
        }
    }

    return 'en';
}

/**
 * @return array{code:string,name:string,dir:string,strings:array<string,string>}
 */
function deliveries_feedback_lang_pack(string $code): array
{
    $langs = deliveries_feedback_languages();
    $code = isset($langs[$code]) ? $code : 'en';
    $pack = $langs[$code];

    return [
        'code' => $code,
        'name' => $pack['name'],
        'dir' => $pack['dir'],
        'strings' => $pack['strings'],
    ];
}

function deliveries_feedback_t(array $strings, string $key, string $fallback = ''): string
{
    if (isset($strings[$key]) && $strings[$key] !== '') {
        return (string) $strings[$key];
    }

    return $fallback !== '' ? $fallback : $key;
}
